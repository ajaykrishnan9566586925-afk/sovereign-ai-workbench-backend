from typing import Any, Optional

from pydantic import BaseModel, Field


class AgentRequest(BaseModel):
    request_id: Optional[str] = Field(
        default=None,
        description="Optional request ID generated by frontend/backend",
    )

    user_input: str = Field(
        ...,
        min_length=1,
        description="User instruction or question",
    )

    input_type: str = Field(
        default="text",
        description="text, image, excel, csv, code, report",
    )

    metadata: dict[str, Any] = Field(
        default_factory=dict,
        description="Local metadata such as local file_path or user role",
    )


class AgentResponse(BaseModel):
    success: bool
    request_id: str
    status: str
    task_category: Optional[str] = None
    model_to_use: Optional[str] = None
    route_reason: Optional[str] = None

    final_answer: Optional[str] = None
    structured_output: dict = Field(default_factory=dict)

    evidence_items: list[dict] = Field(default_factory=list)
    evidence_confidence: float = 0.0
    evidence_verified: bool = False

    needs_human_approval: bool = False
    approval_reason: Optional[str] = None

    tool_results: list[dict] = Field(default_factory=list)
    progress_events: list[dict] = Field(default_factory=list)
    audit_events: list[dict] = Field(default_factory=list)

    retry_count: int = 0
    error_message: Optional[str] = None


class ApprovalRequest(BaseModel):
    request_id: str
    approval_status: str = Field(
        ...,
        description="approved or rejected",
    )